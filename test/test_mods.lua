-- v0.4: your mods. Picked on MODS (slot -> group -> mod), written into the launch build's Affixes at launch, cleared
-- from the AI racers' race copies at load (yours kept), put back at the menu. 50cc: no mods at all.
local M = require('mock')
local W = require('world')
local T = require('util')
T.boot(nil, { Progression = { On = false } })
M.press('F6'); M.tick(6)
T.clickTitle('150CC'); M.tick(3)
T.clickTitle('JAKKU CUP'); M.tick(3)
T.clickTitle('MODS'); M.tick(3)
T.check(T.titles() == 'EMPTY SLOT|EMPTY SLOT|EMPTY SLOT|DONE', '150cc: three empty mod slots (' .. T.titles() .. ')')
T.clickTitle('EMPTY SLOT'); M.tick(3)
T.check(T.titles():find('^AFTERBURNER|RAMJET|COOLING & HEAT') ~= nil and T.titles():find('BACK$') ~= nil, 'the groups (' .. T.titles() .. ')')
T.clickTitle('STATUS PROTECTION'); M.tick(3)
T.check(T.titles():find('FROST PROTECTION', 1, true) ~= nil, 'Frost Protection on offer')
T.clickTitle('FROST PROTECTION'); M.tick(3)
T.check(T.titles() == 'FROST PROTECTION|EMPTY SLOT|EMPTY SLOT|DONE', 'slot 1 fitted (' .. T.titles() .. ')')
T.check(T.badges():find('^PROTECTION|SLOT 2') ~= nil, 'badges: PROTECTION, SLOT 2 (' .. T.badges() .. ')')
T.click(2); M.tick(3)
T.clickTitle('STATUS PROTECTION'); M.tick(3)
T.check(not T.titles():find('FROST PROTECTION', 1, true), 'slot 2: Frost Protection not offered again (one per effect)')
T.clickTitle('BACK'); M.tick(3)
T.clickTitle('COOLING & HEAT'); M.tick(3)
T.clickTitle('COOLING SLIPSTREAM'); M.tick(3)
T.check(T.titles() == 'FROST PROTECTION|COOLING SLIPSTREAM|EMPTY SLOT|DONE', 'slot 2 fitted (' .. T.titles() .. ')')
local sv = T.save().mods
T.check(sv[1] == 'Conditions_FreezeProtection' and sv[2] == 'Cooled_GainWhileSlipstream' and sv[3] == false, 'mods saved')

T.clickTitle('DONE'); M.tick(3)
T.clickTitle('START CUP')
local aff = W.buildAffixes.VBD_Car_Base
local function names(l) local o = {}; for i, a in ipairs(l) do o[i] = rawget(a, '__name') end; return table.concat(o, ',') end
T.check(names(aff) == 'AFX_Conditions_FreezeProtection,AFX_Cooled_GainWhileSlipstream', 'launch build: your two mods (' .. names(aff) .. ')')
T.check(T.logHas('your mods for this race: AFX_Conditions_FreezeProtection, AFX_Cooled_GainWhileSlipstream'), 'logged')
T.check(T.save().run.mods[2] == 'Cooled_GainWhileSlipstream', 'the cup keeps its own copy of the mods')
T.check(T.save().modRestores.VBD_Car_Base == nil and next(T.save().modRestores) ~= nil, 'the build\'s own list saved before the race')

W.race(11); M.tick(5)
T.check(T.logHas('your mods cleared from the AI racers\' copies: 88 slots'), 'cleared from 11 bots x 4 copies x 2 mods')
T.check(W.affixes(W.bots[1]) == '-,-,-,-' and W.affixes(W.bots[11]) == '-,-,-,-', 'bots: no mods (' .. W.affixes(W.bots[1]) .. ')')
T.check(W.affixes(W.player) == 'AFX_Conditions_FreezeProtection,AFX_Cooled_GainWhileSlipstream,-,-', 'you: your mods (' .. W.affixes(W.player) .. ')')
W.finish(2); M.tick(25)
local t0 = os.time(); while os.time() - t0 < 3 do end
W.backToMenu(); M.tick(45)
T.check(#aff == 0, 'launch build: mods put back after the race (' .. #aff .. ' left)')
T.check(T.logHas('mods put back (main menu): VBD_Car_Base (0)'), 'put back logged')
T.check(next(T.save().modRestores) == nil, 'nothing left to put back')

-- 50cc: pure driving
T.clickTitle('LATER'); M.tick(3)
T.clickTitle('QUIT CUP'); M.tick(3)
T.clickTitle('YES'); M.tick(3)
T.clickTitle('BACK'); M.tick(3)
T.clickTitle('50CC'); M.tick(3)
T.clickTitle('JAKKU CUP'); M.tick(3)
T.clickTitle('MODS'); M.tick(3)
T.check(T.titles():find('^START CUP') ~= nil, '50cc: MODS doesn\'t open (no slots)')
local mark = T.mark()
T.clickTitle('START CUP')
T.check(#aff == 0 and not T.logHas('your mods for this race', mark), '50cc: no mods on the build, none logged')
T.finish()
