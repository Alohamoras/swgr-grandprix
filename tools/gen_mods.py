#!/usr/bin/env python3
"""Make mod/GalacticGrandPrix/Scripts/mods.lua (the MODS catalogue) from the recon data:
tools/recon/ModRecon/affixes.tsv (every affix, read in game) + catalogue.json (groups and tags).
Kept: tag 'protect' and 'style' (owner, 2026-11-10: no pure-power mods, no podracer ones). Top step everywhere."""
import csv, json, re, os
HERE = os.path.dirname(os.path.abspath(__file__))
REC = os.path.join(HERE, 'recon', 'ModRecon')
OUT = os.path.join(HERE, '..', 'mod', 'GalacticGrandPrix', 'Scripts', 'mods.lua')
rows = {r['asset']: r for r in csv.DictReader(open(os.path.join(REC, 'affixes.tsv')), delimiter='\t')}
cat = json.load(open(os.path.join(REC, 'catalogue.json')))
def clean(s):
    s = re.sub(r'<widget id="[^"]*"/>', '', s); s = re.sub(r'<H1>(.*?)</>', r'\1', s)
    return re.sub(r'\s+', ' ', s).strip()
def nums(m):
    d = {}
    for kv in m.split():
        k, v = kv.split('='); d[k] = int(v)
    return d
def fill(r):
    s = clean(r['description'])
    for k, v in nums(r['percent']).items(): s = s.replace('{' + k + '}', f'{v}%')
    for k, v in nums(r['int']).items(): s = s.replace('{' + k + '}', f'{v} kph' if k == 'speed' else str(v))
    s = s.replace('Nones', 'the whole race')  # "for 30 / 60 / Nones" (no limit at the top step)
    assert '{' not in s, (r['asset'], s)
    return s
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
groups, effects = [], []
for g, fs in cat['groups'].items():
    kept = [f for f in fs if f['tag'] in ('protect', 'style')]
    if not kept: continue
    groups.append(g)
    for f in kept:
        top = rows[f['assets'][-1]]
        effects.append((f['key'][4:], re.sub(r'\s+[IVX]+$', '', top['name']), g, fill(top), top['asset'], top['path'], f['tag'], f['strong'], top['rarity']))
L = ['-- Galactic Grand Prix: the MODS catalogue (v0.4). GENERATED by tools/gen_mods.py from the in-game recon',
     '-- (tools/recon/ModRecon, 2026-11-10) - edit the tags there and regenerate, not here.',
     '-- Owner, 2026-11-10: mods change how you race, not how fast - protections / rule-changers and playstyle mods only',
     '-- (no pure-power or podracer ones), each at its top step. strong = a big payoff, kept by the owner ("check").',
     'return {', '  groups = { ' + ', '.join(q(g) for g in groups) + ' },', '  effects = {']
for k, n, g, d, a, p, t, s, rar in effects:
    L.append(f'    {{ key = {q(k)}, name = {q(n)}, group = {q(g)}, tag = {q(t)}, strong = {str(s).lower()}, rarity = {q(rar)},')
    L.append(f'      desc = {q(d)},')
    L.append(f'      path = {q(p)} }},')
L += ['  },', '}', '']
open(OUT, 'w').write('\n'.join(L))
print(len(effects), 'effects in', len(groups), 'groups ->', os.path.normpath(OUT))
